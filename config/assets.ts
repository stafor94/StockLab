import type { AssetCurrency, AssetKind, MarketCode } from '../src/types/market'

export interface CatalogAsset {
  id: string
  alias: string
  kind: AssetKind
  market: MarketCode
  currency: AssetCurrency
  sector: string
  listedFrom: string
  dataPath: string
}

type CatalogSeed = readonly [id: string, alias: string, sector: string]

const COVERAGE_START = '2018-01-01'

function expand(
  seeds: CatalogSeed[],
  market: MarketCode,
  kind: AssetKind,
): CatalogAsset[] {
  const currency: AssetCurrency = market === 'KR' ? 'KRW' : 'USD'
  const folder = kind === 'stock' ? 'stocks' : 'etf'
  const marketFolder = market.toLowerCase()

  return seeds.map(([id, alias, sector]) => ({
    id,
    alias,
    kind,
    market,
    currency,
    sector,
    listedFrom: COVERAGE_START,
    dataPath: `${folder}/${marketFolder}/${id}.json`,
  }))
}

